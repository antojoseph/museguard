"""Create eight reusable in-place walk loops without changing the scene stage.

Execute inside the already prepared cream-mascot-locomotion.blend.  The active
combined action, the current frame, and the displayed pose are restored.  This
script creates actions and an embedded playback note; the caller saves later.
"""

import bpy
import json
import math
import sys
from pathlib import Path
from mathutils import Matrix, Vector

ROOT = Path('/Users/x/Documents/Codex/2026-10-30/referenced-chatgpt-conversation-this-is-an')
if str(ROOT / 'work') not in sys.path:
    sys.path.insert(0, str(ROOT / 'work'))
from locomotion_math import gait_ankle_target, two_bone_ik, bone_target_matrix

scene = bpy.context.scene
rig = bpy.data.objects.get('Mascot Rig')
assert rig is not None and rig.type == 'ARMATURE', 'Open the prepared mascot rig first.'
assert Path(bpy.data.filepath).name == 'cream-mascot-locomotion.blend', 'Use the separate locomotion project.'
assert rig.animation_data and rig.animation_data.action, 'Keep the combined showcase action active before running this script.'

SPEED = .10
PERIOD = 1.0
FPS = 24
DUTY = .62
LIFT = .016
TAG = 'mascot.inplacewalk.v1'
CLIPS = [
    ('Forward', (0, -1, 0)),
    ('Backward', (0, 1, 0)),
    ('Left', (-1, 0, 0)),
    ('Right', (1, 0, 0)),
    ('Forward left', (-1, -1, 0)),
    ('Forward right', (1, -1, 0)),
    ('Back left', (-1, 1, 0)),
    ('Back right', (1, 1, 0)),
]

bones = list(rig.pose.bones)
rest = {pb.name: pb.bone.matrix_local.copy() for pb in bones}
heads = {pb.name: pb.bone.head_local.copy() for pb in bones}
lengths = {pb.name: pb.bone.length for pb in bones}
feet = {side: heads['Foot.' + side].copy() for side in ('L', 'R')}
phases = {'L': 0.0, 'R': .5}
head = rig.pose.bones['Head']
face_values = {'Blink': 0.0, 'Blink Left': 0.0, 'Blink Right': 0.0, 'Smile': .12}
assert all(prop in head for prop in face_values), 'The rig must already have its facial controls.'

old_action = rig.animation_data.action
old_slot = rig.animation_data.action_slot
old_frame = scene.frame_current
old_subframe = scene.frame_subframe
old_basis = {pb.name: pb.matrix_basis.copy() for pb in bones}
old_modes = {pb.name: pb.rotation_mode for pb in bones}
old_face = {prop: head[prop] for prop in face_values}
old_frame_range = (scene.frame_start, scene.frame_end)
report = {
    'loop_count': 8,
    'fps': FPS,
    'period_seconds': PERIOD,
    'keyed_frames': [1, 25],
    'period_frames': 24,
    'runtime_translation_metres_per_second': SPEED,
    'active_action_preserved': old_action.name,
    'clips': [],
}


def turn_at(point, axis, angle):
    return Matrix.Translation(point) @ Matrix.Rotation(angle, 4, axis) @ Matrix.Translation(-point)


def linear_keys(action):
    for layer in action.layers:
        for strip in layer.strips:
            for bag in strip.channelbags:
                for curve in bag.fcurves:
                    for key in curve.keyframe_points:
                        key.interpolation = 'LINEAR'


try:
    for label, direction_values in CLIPS:
        action_name = 'Walk loop - ' + label
        existing = bpy.data.actions.get(action_name)
        if existing is not None:
            assert existing.get('Generated by') == TAG, 'An unrelated action already uses ' + action_name
            assert existing != old_action, 'The combined showcase must remain the active source action.'
            bpy.data.actions.remove(existing)
        action = bpy.data.actions.new(action_name)
        action.use_fake_user = True
        action['Generated by'] = TAG
        action['Description'] = 'In-place planted-foot walk; the native app translates the character at 0.10 metres/second.'
        action['Period seconds'] = PERIOD
        action['Period frames'] = 24
        action['Keyed frames'] = '1 through 25; frame 25 repeats frame 1.'
        action['Frames per second'] = FPS
        action['Root motion'] = 'None. Animate the app entity along the direction vector.'
        direction = Vector(direction_values).normalized()
        velocity = direction * SPEED
        action['Direction vector'] = list(direction)
        action['Runtime speed m/s'] = SPEED
        rig.animation_data.action = action

        previous_quaternions = {}
        endpoint = {}
        stats = {
            'name': action_name,
            'direction': list(direction),
            'maximum_reach_error_metres': 0.0,
            'maximum_baked_ankle_error_metres': 0.0,
            'maximum_scale_error': 0.0,
            'minimum_body_crouch_metres': 0.0,
        }

        def root_path(time):
            return velocity * time

        for index in range(FPS + 1):
            time = index / FPS
            frame = index + 1
            phase = math.tau * time
            root_motion = root_path(time)
            targets = {
                side: gait_ankle_target(time, root_path, velocity, feet[side],
                                        phase=phases[side], cycle=PERIOD,
                                        duty=DUTY, lift=LIFT) - root_motion
                for side in ('L', 'R')
            }
            roll = math.radians(1.1) * math.sin(phase)
            twist = math.radians(.8) * math.sin(phase)
            crouch = -.010 - .002 * math.sin(phase * 2) ** 2
            body_zero = turn_at(heads['Body'], 'Y', roll)
            # A short leg can require a little additional lowering during a
            # diagonal swing.  The feet stay fixed relative to the moving app.
            ceiling = 0.0
            for side in ('L', 'R'):
                hip = body_zero @ heads['Leg.' + side]
                ankle = targets[side]
                reach = lengths['Leg.' + side] + lengths['Shin.' + side] - .0004
                horizontal_sq = (ankle.x - hip.x) ** 2 + (ankle.y - hip.y) ** 2
                assert horizontal_sq < reach ** 2, (label, frame, side, 'Horizontal reach')
                ceiling = min(ceiling, ankle.z + math.sqrt(reach ** 2 - horizontal_sq) - hip.z)
            crouch = min(crouch, ceiling)
            stats['minimum_body_crouch_metres'] = min(stats['minimum_body_crouch_metres'], crouch)

            body_transform = Matrix.Translation((0, 0, crouch)) @ body_zero
            chest_transform = body_transform @ turn_at(heads['Chest'], 'Z', twist)
            head_transform = chest_transform @ turn_at(heads['Head'], 'Y', -roll * .65)
            transforms = {'Root': Matrix.Identity(4), 'Body': body_transform,
                          'Chest': chest_transform, 'Head': head_transform}
            arm_axis = Vector((direction.y, -direction.x, 0))
            for side, sign in (('L', 1), ('R', -1)):
                arm_angle = math.radians(9) * math.sin(phase) * sign
                fore_angle = -math.radians(3) * abs(math.sin(phase))
                arm_transform = chest_transform @ turn_at(heads['Arm.' + side], arm_axis, arm_angle)
                fore_transform = arm_transform @ turn_at(heads['Forearm.' + side], 'X', fore_angle)
                transforms['Arm.' + side] = arm_transform
                transforms['Forearm.' + side] = fore_transform
                transforms['Hand.' + side] = fore_transform
            desired = {name: transform @ rest[name] for name, transform in transforms.items()}
            for side in ('L', 'R'):
                hip = body_transform @ heads['Leg.' + side]
                ankle = targets[side]
                knee, error = two_bone_ik(hip, ankle, lengths['Leg.' + side],
                                           lengths['Shin.' + side], Vector((0, -1, 0)))
                assert error < .00001, (label, frame, side, 'Unreachable ankle', error)
                stats['maximum_reach_error_metres'] = max(stats['maximum_reach_error_metres'], error)
                desired['Leg.' + side] = bone_target_matrix(rest['Leg.' + side], hip, knee - hip)
                desired['Shin.' + side] = bone_target_matrix(rest['Shin.' + side], knee, ankle - knee)
                foot_matrix = rest['Foot.' + side].copy()
                foot_matrix.translation = ankle
                desired['Foot.' + side] = foot_matrix

            frame_state = {}
            reconstructed = {}
            for pb in bones:
                parent = pb.parent
                base = (desired[parent.name] @ rest[parent.name].inverted() @ rest[pb.name]
                        if parent else rest[pb.name])
                basis = base.inverted() @ desired[pb.name]
                location, quaternion, scale = basis.decompose()
                stats['maximum_scale_error'] = max(stats['maximum_scale_error'],
                                                   max(abs(value - 1) for value in scale))
                assert max(abs(value - 1) for value in scale) < .00001, (label, frame, pb.name, 'Scale')
                if pb.name in previous_quaternions and quaternion.dot(previous_quaternions[pb.name]) < 0:
                    quaternion.negate()
                previous_quaternions[pb.name] = quaternion.copy()
                pb.rotation_mode = 'QUATERNION'
                pb.location = location
                pb.rotation_quaternion = quaternion
                pb.scale = (1, 1, 1)
                pb.keyframe_insert('location', frame=frame, group=pb.name)
                pb.keyframe_insert('rotation_quaternion', frame=frame, group=pb.name)
                frame_state[pb.name] = (location.copy(), quaternion.copy())
                # Algebraic FK checks the actual written local channels without
                # forcing expensive evaluation of the million-strand groom.
                fk_base = (reconstructed[parent.name] @ rest[parent.name].inverted() @ rest[pb.name]
                           if parent else rest[pb.name])
                reconstructed[pb.name] = fk_base @ Matrix.LocRotScale(location, quaternion, Vector((1, 1, 1)))
            for side in ('L', 'R'):
                error = (reconstructed['Foot.' + side].translation - targets[side]).length
                stats['maximum_baked_ankle_error_metres'] = max(stats['maximum_baked_ankle_error_metres'], error)
                assert error < .00001, (label, frame, side, 'Baked ankle', error)
            for prop, value in face_values.items():
                head[prop] = value
                head.keyframe_insert(data_path='["' + prop + '"]', frame=frame, group='Face')
            if index in (0, FPS):
                endpoint[index] = frame_state

        max_location = 0.0
        max_quaternion = 0.0
        for name in rest:
            first_location, first_quaternion = endpoint[0][name]
            last_location, last_quaternion = endpoint[FPS][name]
            max_location = max(max_location, (last_location - first_location).length)
            max_quaternion = max(max_quaternion,
                                 max(abs(last_quaternion[i] - first_quaternion[i]) for i in range(4)))
        assert max_location < .00001, (label, 'Loop endpoint location mismatch', max_location)
        assert max_quaternion < .00001, (label, 'Loop endpoint quaternion mismatch', max_quaternion)
        stats['endpoint_location_error_metres'] = max_location
        stats['endpoint_quaternion_component_error'] = max_quaternion
        linear_keys(action)
        report['clips'].append(stats)

    text = bpy.data.texts.get('WALK LOOPS - app playback guide') or bpy.data.texts.new('WALK LOOPS - app playback guide')
    text.clear()
    text.write(
        'EIGHT IN-PLACE WALK LOOPS\n'
        'Free native Blender skeleton animation; no rig add-on dependency.\n'
        'Actions: Walk loop - Forward, Backward, Left, Right, Forward left, Forward right, Back left, Back right.\n'
        'Every loop lasts 1 second at 24 fps. Keys run from frame 1 through frame 25; frame 25 repeats frame 1.\n'
        'When sampling discrete frames, render/play frames 1-24 and wrap to frame 1. For an exported continuous clip, use the full 1-25 range for a 1-second period.\n'
        'The skeleton root stays in place. The native app must translate the character entity at 0.10 metres/second along the action direction vector for planted feet.\n'
        'Directions use model coordinates: forward is -Y, right is +X, up is +Z; convert to the app coordinate convention when exporting.\n'
        'The avatar keeps facing forward during side/backward/diagonal loops. Rotate the app entity to change its facing, and rotate its travel direction with it.\n'
        'Feet are solved analytically with overlapping stance, a short lift, and level soles. Blinking is off; smile is 0.12 so the app can layer expressions.\n'
        'The combined direction-and-stair showcase action remains active. Pick a Walk loop action and frames 1-25 in the Action Editor to preview a reusable loop.\n'
        'These Blender strand curves still need a separate real-time fur conversion before native-app export.\n'
    )
finally:
    rig.animation_data.action = old_action
    if old_slot is not None:
        rig.animation_data.action_slot = old_slot
    scene.frame_start, scene.frame_end = old_frame_range
    scene.frame_set(old_frame, subframe=old_subframe)
    for pb in bones:
        pb.rotation_mode = old_modes[pb.name]
        pb.matrix_basis = old_basis[pb.name]
    for prop, value in old_face.items():
        head[prop] = value
    rig.update_tag(refresh={'OBJECT', 'DATA', 'TIME'})

assert rig.animation_data.action == old_action, 'The combined showcase action must remain active.'
assert (scene.frame_current, scene.frame_subframe) == (old_frame, old_subframe), 'The displayed frame must be restored.'
print(json.dumps(report))
